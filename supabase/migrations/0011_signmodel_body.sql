-- 0011_signmodel_body.sql — 간판 종류에 «손님이 읽을 설명» 칸 추가 (제품 상세페이지)
--
-- 무엇: `content_blocks` 에 `body` 한 칸을 붙이고, `sign_model` 9종의 설명을 채웁니다.
--       표를 새로 만들지 않습니다 — 0005 가 "한 표에 구역을 나눠 담는다" 로 정했고,
--       칸 하나가 표 하나보다 훨씬 쌉니다.
--
-- 왜:   2026-09-09. 제품 상세페이지(`/products/<슬러그>`)를 만들면서 필요해졌습니다.
--       그전까지 간판 한 종류가 들고 있는 글자는 **이름·T번호·가격대**뿐이라,
--       상세페이지를 만들어도 9장이 거의 똑같은 화면이 됩니다. 🔴 **내용이 없는데
--       주소만 아홉 개 생기면 검색엔진에 «얇은 중복 페이지» 아홉 장이 됩니다** —
--       그래서 이 칸이 비어 있으면 그 페이지는 색인 대상에서 빠지고 사이트맵에도
--       안 들어갑니다(`app/products/[slug]/page.tsx`).
--
-- 칸의 뜻:
--   body = 손님이 읽는 설명. 문단 여러 개(빈 줄로 나눔) 가능.
--          🔴 **가격·기간을 약속하는 문장을 쓰지 마세요.** 현장마다 갈리는 값이라
--          화면의 다른 문구(“정확한 사양과 금액은 현장을 보고 정합니다”)와 부딪힙니다.
--          다른 구역(`why`·`process` 등)에서는 아직 안 씁니다 — 빈 문자열입니다.
--          ⚠️ **화면은 이 글을 «있는 그대로» 그립니다** — `**굵게**` 같은 마크다운이나
--          이모지를 넣어도 기호가 그대로 보입니다. 빈 줄로 문단만 나뉩니다.
--
-- 🔴 **아래 9개 설명은 «초안»입니다. 대표님이 관리자 화면에서 고치세요**
--    (`/admin/content?section=sign_model` → 각 항목의 “손님용 설명”).
--    지어낸 문장이 아니라 형제 저장소 `DeGaJa_Agent` 의
--    `users/hanjeonghyun/domains/susanna/SIGNTYPES.md` §3·§9 와 이미 DB 에 들어 있는
--    제작 사양(`points[0]`)에서 **사실만** 옮긴 것입니다 [P6]. 그래도 «이 회사가 손님에게
--    할 말»은 대표님 것이라, 코드가 아니라 고칠 수 있는 자리에 넣었습니다.
--    ⚠️ 업종·용도를 단정하는 문장("○○ 업종에 많이 씁니다")은 일부러 안 넣었습니다 —
--    출처에 없는 말이라 지어내면 P6 위반입니다.
--
-- ⚠️ **이미 채워진 설명은 안 덮어씁니다** (`where body = ''`). 대표님이 고친 뒤에
--    이 파일을 다시 돌려도 그 글이 안 날아갑니다. 재실행해도 안전합니다.
--
-- 실행: Supabase 대시보드 → SQL Editor → 붙여넣고 RUN

alter table public.content_blocks
  add column if not exists body text not null default '';


update public.content_blocks as b
   set body = v.body
  from (values
    ('channel-front',
     '글자 앞면이 빛나는 가장 대중적인 방식입니다. 알루미늄 채널 옆면에 전면 아크릴을 끼워 만들고, 야간 시인성이 아홉 가지 중 가장 좋습니다.

글자 뒤에 전기선을 가리는 바가 들어갑니다. 정면이 잘 보이는 1층 상가에서 가장 많이 쓰는 구성입니다.'),

    ('channel-halo',
     '빛이 글자 뒤로 나와 벽을 밝힙니다. 벽에서 띄워 달기 때문에 피스가 겉으로 보이지 않고, 눈부심이 적어 차분하게 읽힙니다.

배선을 인테리어 단계부터 같이 잡아야 합니다. 나중에 손대면 전선이 겉으로 지저분하게 남습니다.'),

    ('channel-both',
     '앞면과 뒷면이 함께 빛납니다. 글자 자체의 밝기와 벽에 번지는 빛을 한 번에 씁니다.

전면발광보다 두껍게 만들고 벽에서도 띄웁니다.'),

    ('scasi',
     '빛 없이 입체감만으로 읽는 글자입니다. 그림자로 읽혀 차분하고, 조명 부품이 없어 아홉 가지 중 수명이 가장 깁니다(7~10년).

아크릴·포멕스·목재·금속 등 재료 선택의 폭이 넓습니다.'),

    ('facade',
     '벽에 갈바 통판을 먼저 세우고 그 위에 글자를 얹습니다.

벽면이 고르지 않거나 타일·벽돌이라 글자를 직접 붙이기 어려울 때, 또는 면 전체를 브랜드 색으로 덮고 싶을 때 씁니다.'),

    ('projecting',
     '벽에서 직각으로 튀어나오게 답니다.

정면이 아니라 길을 따라 걸어오는 사람에게 보이는 것이 목적이라, 골목이나 상가 통로에서 정면 간판이 안 보이는 자리에 씁니다.'),

    ('rooftop',
     '건물 옥상에 철골 구조를 세워 올립니다. 멀리서 보이는 것이 목적입니다.

구조 검토와 사전 심의 대상이고 고소작업 장비가 들어갑니다. 그래서 다른 종류보다 준비 기간이 깁니다 — 일정이 정해져 있으면 미리 알려 주세요.'),

    ('hanging',
     '처마나 캐노피 아래에 봉 두 개로 매답니다.

벽에 구멍을 내기 어렵거나 이미 처마가 있는 자리에서 씁니다. 판과 글자는 외벽사인과 같은 방식으로 만들고 거는 방법만 다릅니다.'),

    ('bracket',
     '레이저로 자른 철판을 환봉으로 벽에서 띄워 답니다. 무점등입니다.

낮에는 햇빛이, 밤에는 외부 조명이 만드는 그림자로 읽힙니다. 띄워서 생기는 그림자 자체가 이 방식의 인상입니다.')
  ) as v(slug, body)
 where b.section = 'sign_model'
   and b.slug = v.slug
   and b.body = '';        -- 🔴 이미 쓰신 글은 안 건드립니다
