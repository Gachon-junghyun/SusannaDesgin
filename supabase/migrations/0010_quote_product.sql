-- 0010_quote_product.sql — 견적 문의에 «어느 제품을 보고 왔나» 칸 추가
--
-- 무엇: `quotes` 에 `product` 한 칸을 붙입니다. 표를 새로 만들지 않습니다 —
--       문의 한 건에 딸린 값이라 같은 행에 있는 게 맞고, 표를 늘리면 RLS·관리자
--       화면·알림 메일이 한 벌씩 더 생깁니다.
--
-- 왜:   2026-09-09. `/products` 를 손님에게 열면서(F24 `SHOW_PRODUCTS` → true)
--       카드마다 「이 간판 견적 받기」 버튼이 `/quote` 로 보내는데, 지금까지는
--       **어느 카드를 눌러서 온 문의인지 아무 데도 안 남았습니다.** 전화로 다시
--       물어야 하고, 그 사이 손님은 다른 곳에 견적을 받습니다.
--
-- 칸의 뜻:
--   product = 손님이 누른 카드의 이름. 예: "전면발광 채널 (T1)"
--             🔴 **`sign_type`(문의 분야)과 다릅니다.** 저건 손님이 폼에서 고른
--             네 가지(옥외광고물·간판디자인·철구조물·옥내광고물·기타)이고,
--             이건 **제품 카탈로그에서 실제로 누른 카드**입니다. 축이 달라서
--             한 칸에 합치지 않았습니다 — T7(옥상광고탑)은 «옥외광고물»이고
--             T1(전면발광 채널)은 «간판디자인» 이라, 합치면 둘 중 하나가 사라집니다.
--             빈 문자열이면 «카드를 안 거치고 그냥 견적 폼으로 들어온 문의» 입니다.
--
-- 🔴 **값은 카드 목록에서 확인한 것만 들어갑니다.** 홈페이지가 주소창의 `?item=<슬러그>`
--    를 `content_blocks` 의 실제 행과 대조해서 이름으로 바꿔 폼에 얹습니다
--    (`app/quote/page.tsx`). 손님이 주소를 손으로 고쳐도 목록에 없는 슬러그면
--    아무것도 안 붙습니다 [P6]. 그래도 API 는 길이·제어문자를 한 번 더 자릅니다.
--
-- ⚠️ **안 돌려도 문의는 안 잃습니다.** `app/api/quote/route.ts` 가 이 칸이 없는 DB 를
--    만나면 그 칸만 빼고 한 번 더 넣습니다(로그에 크게 남깁니다). 대신 **돌리기
--    전까지는 어느 제품을 보고 왔는지가 안 쌓입니다** — 알림 메일에는 그때도 나갑니다.
--
-- 실행: Supabase 대시보드 → SQL Editor → 붙여넣고 RUN
-- 여러 번 실행해도 안전합니다.

alter table public.quotes
  add column if not exists product text not null default '';
